        <h2 id="about-heading">آنچه ما را<br /><em>به هم پیوند می‌دهد.</em></h2>
      </div>
      <div class="about-prose prose">
        <p>اعتماد و آسایش ایرانیان بر پایه یک نگاه سازمانی به توسعه فعالیت‌های تخصصی شکل گرفته است؛ نگاهی که ارزش هر کسب‌وکار را در هویت، تجربه و توانایی مستقل آن می‌بیند و در عین حال، به ظرفیت‌های حاصل از قرارگرفتن مجموعه‌های مختلف در یک ساختار مشترک توجه دارد.</p>
        <p>ما معتقدیم توسعه پایدار یک گروه، تنها به گسترش تعداد فعالیت‌ها وابسته نیست. آنچه اهمیت دارد، شکل‌دادن به روابطی روشن میان شرکت‌ها، شناخت فرصت‌های رشد و ایجاد شرایطی است که هر مجموعه بتواند در حوزه تخصصی خود جایگاه مشخص و قابل اتکایی داشته باشد.</p>
        <p>نقش اعتماد و آسایش ایرانیان در این ساختار، فراتر از معرفی مجموعه‌های زیرمجموعه است. شرکت مادر، مسئولیت هدایت مسیر کلان گروه، توجه به ظرفیت‌های مشترک و نگاه بلندمدت به توسعه فعالیت‌ها را بر عهده دارد.</p>
        <p>استقلال شرکت‌ها در ارائه خدمات و ارتباط با مخاطبان حفظ می‌شود و در سطح گروه، تلاش بر ایجاد هماهنگی میان مسیرهای توسعه، استفاده از تجربه‌های تخصصی و شناسایی فرصت‌های تازه است.</p>
