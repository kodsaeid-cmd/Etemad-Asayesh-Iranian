        <h3>نگاه ما به آینده</h3>
        <div class="prose">
          <p>آینده خدمات، تنها در افزایش تعداد ارائه‌دهندگان یا توسعه ابزارهای دیجیتال خلاصه نمی‌شود. تغییر نیازهای خانواده‌ها، اهمیت کیفیت تجربه دریافت خدمت، جایگاه آموزش و نقش فناوری، همگی بر شیوه فعالیت کسب‌وکارهای این حوزه اثر می‌گذارند.</p>
          <p>اعتماد و آسایش ایرانیان، توسعه خود را در شناخت این تغییرات و ایجاد ظرفیت پاسخ‌گویی به آن‌ها دنبال می‌کند؛ با حفظ هویت شرکت‌های موجود و توجه به فرصت‌هایی که می‌توانند افق فعالیت گروه را گسترده‌تر کنند.</p>
